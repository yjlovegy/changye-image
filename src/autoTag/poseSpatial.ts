/** Prompt guidance, not a skeleton controller or a semantic validator of generated pixels. */
export function poseSpatialContract(options: {
  mixed: boolean;
  characterPrompts: boolean;
  negativeRequired: boolean;
}): string {
  return `【姿势与空间关系优先】
以下规则优先于旧规范中先铺陈五官、服装和背景再交代动作的写法；仍须保留已确定且可见的身份与面部特征。先确定一个瞬间的动作和空间结构，再为它补外貌细节。用户明确的姿势、接触关系和相对位置优先于审美偏好；不能为了露脸、构图好看或丰富场景改写动作。
在内部做一次简短关系核对，不输出推理或另加 JSON 字段：
- 主体和坐标：先确定人数与区分性称谓；screen left/right 指画面左右，their left/right 指该角色自身左右。多人各自的左右独立，不能把一个人的左手变成另一个人的手。正文未确定且不影响动作的侧别不硬加；确需选择时确定一套并在 tag/nl 一致复用。
- 整体姿态：躯干是直立、前倾、后仰还是横向，头、肩与骨盆的相对方向如何，人物面朝哪个对象。相机俯视不是人物弯腰，侧面镜头不是人物扭头，人物在前景也不表示身体前倾。镜头方向与身体方向分别表达。
- 肢体位置：只展开动作必需且可见的手脚；说明左右臂/腿的伸展或弯曲、手脚相对肩/胸/髋/地面的高度及方向。抽象动作名和文学比喻必须转成能画出的肢体关系，不能只直译一个姿势名称。不要同时写同一条肢体伸直又弯曲，或让同一只手执行互斥任务。
- 支撑与接触：分清承重、轻触、握持以及彼此分离。坐着要明确实际座面或承重物与必要的可见脚部位置，坐地面、台阶不改成椅子，腾跃的瞬间可以没有承重点；手持道具要明确持有者、哪只手和握持位置。依据当前任务提供的剧情或草稿与修改意见确定实际接触点；离开支撑面的肢体要写清相对高度或间隙，不无故添桌椅或地面接触来“补全”姿势。神态词不能替代这些结构。
- 空间关系：用“主体A的部位 → 动作/接触 → 主体B的部位或物件”写清归属；相对位置说出参照物，不能只有 left/right/behind。说明与动作有关的前后遮挡、距离或高低，不堆与动作无关的精确数字。交接物件先选一个时点，双方持有状态必须能同时成立。
${options.characterPrompts
    ? 'NAI Base tag/nl 先交代人数、整体布局、相机和共有互动；每个角色自己的 characters[].tag/nl 才写该角色姿态、肢体、衣服和五官。两边关系一致，不把个人动作塞入 Base，也不把共享关系分配成两个不同事件。角色 tag 保留必要的同人身份首位，其后先写核心姿态/接触，再写外貌细节。'
    : 'tag 排序：人数/必要身份和一个镜头词 → 核心姿态、接触点与空间关系 → 已知可见外貌五官 → 服装、神态视线 → 必要背景光线。动作不是堆在最后的装饰标签；多人物用各自区分性称谓绑定，不能散落无主的手脚词。'}
${options.mixed
    ? 'nl 的开头先用一至两句清楚建立该通道负责的动作与布局，再完整写可见的外貌五官、服装和神态，最后补必要环境。tag 先锁定同一姿态和接触，nl 展开肢体位置及人物归属；两者不能出现相反的躯干朝向、支撑面、手脚状态或物件持有者。'
    : '当前只消费 tag：用简短英文视觉短语直接表达必要的姿态、接触和位置；不能依赖未启用的 nl 来补关键关系。'}
镜头须能验证核心动作：涉及全身或脚部关系时，让相关关节、末端及参照物进入画面并留出边缘空间；局部动作才采用对应局部取景。只选一个相容的景别，不同时要求近脸特写和完整四肢。保持主体动作、重要接触点和身份优先，再删去重复的美化修饰与次要背景；不要为展示五官改变已确定的身体姿态。
${options.negativeRequired
    ? '本图 negative 根据已经确定的姿态与布局排除少量相反状态或易错关系；只用仍适用的排除项，不机械照抄另一张图。不能把正常需要的手脚、椅子或物件本身写成负面，也不能否定 tag/nl 的有效接触。先改正正向内部的矛盾，不能靠负面去抵消正向同时写出的相反姿态。'
    : '当前没有本画面负面输入：在正向内部解决矛盾，不把负面词混入 tag/nl，也不伪造本后端不接收的 negative。'}
最终在内部逐人检查同一瞬间：躯干朝向 → 动作肢体位置 → 实际接触和支撑 → 物件持有者 → 画面相对位置 → 镜头可见范围；再与 tag/nl 逐一比对。保留当前任务原有 JSON 结构，不输出检查表。`;
}
